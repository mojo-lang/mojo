package util

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

const generatedHeader = "// Code generated by mojo. DO NOT EDIT.\n"

func writeTestFile(t *testing.T, dir, name, content string) string {
	t.Helper()
	file := filepath.Join(dir, name)
	require.NoError(t, os.MkdirAll(filepath.Dir(file), 0755))
	require.NoError(t, os.WriteFile(file, []byte(content), 0600))
	return file
}

func TestIsAllGeneratedFile(t *testing.T) {
	for _, tt := range []struct {
		name, content string
		want          bool
	}{
		{"standard", generatedHeader + "package test", true},
		{"legacy", "// Generated by mojo. DO NOT EDIT!", true},
		{"whitespace", "  // Code generated by mojo. DO NOT EDIT.\r\n", true},
		{"empty", "", false},
		{"manual", "package test\n" + generatedHeader, false},
		{"missing warning", "// Code generated by mojo.\n", false},
		{"missing prefix", "// Manual file. DO NOT EDIT.\n", false},
	} {
		t.Run(tt.name, func(t *testing.T) {
			file := writeTestFile(t, t.TempDir(), "source.go", tt.content)
			require.Equal(t, tt.want, IsAllGeneratedFile(file))
		})
	}
	dir := t.TempDir()
	require.False(t, IsAllGeneratedFile(dir))
	require.False(t, IsAllGeneratedFile(filepath.Join(dir, "missing.go")))
}

func TestClearFilesFiltersAndRecursion(t *testing.T) {
	for _, tt := range []struct {
		name                 string
		clear                func(string, ...string) error
		recursive, generated bool
	}{
		{"files", ClearFiles, false, false},
		{"deep files", DeepClearFiles, true, false},
		{"generated", ClearGeneratedFiles, false, true},
		{"deep generated", DeepClearGeneratedFiles, true, true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			for _, name := range []string{"root.go", "nested/child.go", "root.txt"} {
				writeTestFile(t, dir, name, generatedHeader)
			}
			manual := writeTestFile(t, dir, "manual.go", "package manual\n")
			require.NoError(t, tt.clear(dir, ".go"))
			require.NoFileExists(t, filepath.Join(dir, "root.go"))
			require.FileExists(t, filepath.Join(dir, "root.txt"))
			require.DirExists(t, filepath.Join(dir, "nested"))
			if tt.recursive {
				require.NoFileExists(t, filepath.Join(dir, "nested/child.go"))
			} else {
				require.FileExists(t, filepath.Join(dir, "nested/child.go"))
			}
			if tt.generated {
				require.FileExists(t, manual)
			} else {
				require.NoFileExists(t, manual)
			}
		})
	}
}

func TestClearGeneratedFilesWithoutSuffix(t *testing.T) {
	dir := t.TempDir()
	generated := writeTestFile(t, dir, "schema.proto", generatedHeader)
	manual := writeTestFile(t, dir, "manual.go", "package manual\n")
	require.NoError(t, ClearGeneratedFiles(dir))
	require.NoFileExists(t, generated)
	require.FileExists(t, manual)
}

func TestClearFilesMissingDirectory(t *testing.T) {
	for _, clear := range []func(string, ...string) error{ClearFiles, DeepClearFiles, ClearGeneratedFiles, DeepClearGeneratedFiles} {
		err := clear(filepath.Join(t.TempDir(), "missing"), ".go")
		require.ErrorIs(t, err, os.ErrNotExist)
	}
}

func TestGetAbsolutePath(t *testing.T) {
	dir := t.TempDir()
	require.Equal(t, filepath.Join(dir, "schema.mojo"), GetAbsolutePath(dir, "nested/../schema.mojo"))
	abs := filepath.Join(dir, "schema.mojo")
	require.Equal(t, abs, GetAbsolutePath("ignored", abs))
}
