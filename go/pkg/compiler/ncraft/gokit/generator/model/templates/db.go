var d *db.DB
var dOnce sync.Once

func GetDB() *db.DB {
	dOnce.Do(func() {
		cfg := &db.Config{}
		err := config.Get("db").Scan(cfg)
		if err != nil {
			logs.Errorw("failed to get the db config", "error", err)
			panic("failed to get the db config")
		}

		if d = db.New(cfg); d == nil {
			panic("create the db failed")
		}

		// use these options when creating tables
		if cfg.Driver == db.MysqlDriverName {
			d.DB = d.DB.Set("gorm:table_options", "ENGINE=InnoDB CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci")
			sqlDb, err := d.DB.DB()
			if err != nil {
				logs.Warnw("get sqlDb error")
			} else {
				if cfg.GetMaxIdleConnections() != 0 {
					sqlDb.SetMaxIdleConns(int(cfg.GetMaxIdleConnections()))
					logs.Debugw("set mysql max idle connections", "val", cfg.GetMaxIdleConnections())
				}
				if cfg.GetMaxOpenConnections() != 0 {
					sqlDb.SetMaxOpenConns(int(cfg.GetMaxOpenConnections()))
					logs.Debugw("set mysql max open connections", "val", cfg.GetMaxOpenConnections())
				}
			}
		}
	})

	return d
}

func prepareModel(database *db.DB, value interface{}, key string)(string,error){
 if database==nil || database.DB==nil{return "",fmt.Errorf("model: database is not initialized")}
 statement:=&gorm.Statement{DB:database.DB}
 if err:=statement.Parse(value);err!=nil{return "",err}
 field:=statement.Schema.LookUpField(key)
 if field==nil || field.DBName=="" {return "",fmt.Errorf("model: primary key %s has no database column",key)}
 if len(statement.Schema.PrimaryFields)!=1 || statement.Schema.PrimaryFields[0]!=field {
  return "",fmt.Errorf("model: expected %s to be the sole primary key",key)
 }
 if database.Config==nil || !database.Config.DisableAutoMigrate {
  if err:=database.AutoMigrate(value);err!=nil{return "",err}
 }
 return field.DBName,nil
}
