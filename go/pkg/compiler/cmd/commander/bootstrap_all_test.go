package commander

import (
	"os"
	"os/exec"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestBootstrapDefaultRefreshesAllOutputs(t *testing.T) {
	for _, command := range []string{"protoc", "protoc-gen-go", "protoc-gen-go-grpc"} {
		if _, err := exec.LookPath(command); err != nil {
			t.Skipf("integration test requires %s", command)
		}
	}
	root := t.TempDir()
	write := func(name, content string) {
		filename := filepath.Join(root, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(filename), 0755))
		require.NoError(t, os.WriteFile(filename, []byte(content), 0644))
	}
	read := func(name string) string {
		content, err := os.ReadFile(filepath.Join(root, name))
		require.NoError(t, err)
		return string(content)
	}
	write("go/go.mod", "module github.com/mojo-lang/mojo/go\n\ngo 1.24.7\n")
	// Declare the dependent package first to exercise the complete package set.
	write("package.mojo", `package mojo.document {
 repository: 'github.com/mojo-lang/mojo'
 authors: [{organization: 'mojolang.org'}]
 dependencies: {'mojo.core': {repository: 'github.com/mojo-lang/mojo'}}
}
package mojo.core {
 repository: 'github.com/mojo-lang/mojo'
 authors: [{organization: 'mojolang.org'}]
}`)
	write("mojo/core/probe.mojo", "type String\ntype Probe { value: String @1 }")
	write("mojo/document/reference.mojo", "type Reference { probe: mojo.core.Probe @1 }")
	const manualJavaPath = "java/src/main/java/org/mojolang/mojo/core/HandWritten.java"
	const manualJava = "package org.mojolang.mojo.core;\nclass HandWritten {}\n"
	write(manualJavaPath, manualJava)
	require.NoError(t, Bootstrap(filepath.Join(root, "go")))

	outputs := map[string]string{
		"go/pkg/mojo/core/probe.pb.go":                         "GetRevision()",
		"protobuf/mojo/core/probe.proto":                       "string revision = 2;",
		"java/src/main/java/org/mojolang/mojo/core/Probe.java": "getRevision()",
		"document/mojo/core/probe.md":                          "revision",
		"openapi/mojo/core/probe.schema.json":                  "revision",
	}
	// Existing documents and schemas have no generated-code header. They must
	// still be replaced, while Java requires that header to protect user code.
	for name := range outputs {
		require.NotEmpty(t, read(name))
		write(name, "// Code generated by mojo. DO NOT EDIT.\n// stale output\n")
	}
	write("document/mojo/core/probe.md", "stale document without a generated header")
	write("openapi/mojo/core/probe.schema.json", "stale schema without a generated header")
	obsolete := []string{
		"document/mojo/core/removed/child.md",
		"openapi/mojo/core/removed/child.schema.json",
		"openapi/mojo/core/removed/service.yaml",
	}
	for _, name := range obsolete {
		write(name, "obsolete type or service")
	}
	// Protect a handwritten implementation even when its name matches output.
	const referenceJava = "java/src/main/java/org/mojolang/mojo/document/Reference.java"
	const manualReference = "package org.mojolang.mojo.document;\nclass Reference {}\n"
	write(referenceJava, manualReference)
	write("mojo/core/probe.mojo", "type String\ntype Probe { value: String @1\n revision: String @2 }")
	require.NoError(t, Bootstrap(root))
	for name, expected := range outputs {
		require.Contains(t, read(name), expected, name)
		require.NotContains(t, read(name), "stale", name)
	}
	require.Contains(t, read("document/mojo/document/reference.md"), "probe")
	require.Contains(t, read("openapi/mojo/document/reference.schema.json"), "probe")
	require.Equal(t, manualJava, read(manualJavaPath))
	require.Equal(t, manualReference, read(referenceJava))
	for _, name := range obsolete {
		require.NoFileExists(t, filepath.Join(root, name))
	}

	// Explicit language targets retain their selective behavior.
	doc, schema := read("document/mojo/core/probe.md"), read("openapi/mojo/core/probe.schema.json")
	java := read("java/src/main/java/org/mojolang/mojo/core/Probe.java")
	write("mojo/core/probe.mojo", "type String\ntype Probe { value: String @1\n go_only: String @2 }")
	require.NoError(t, Bootstrap(root, "go"))
	require.Contains(t, read("go/pkg/mojo/core/probe.pb.go"), "GetGoOnly()")
	require.Equal(t, doc, read("document/mojo/core/probe.md"))
	require.Equal(t, schema, read("openapi/mojo/core/probe.schema.json"))
	require.Equal(t, java, read("java/src/main/java/org/mojolang/mojo/core/Probe.java"))

	// A later package can fail after core has already generated new documents.
	// Publishing must wait for the entire build to succeed.
	write("mojo/document/reference.mojo", "type Reference { broken: MissingType @1 }")
	require.Error(t, Bootstrap(root))
	require.Equal(t, doc, read("document/mojo/core/probe.md"))
	require.Equal(t, schema, read("openapi/mojo/core/probe.schema.json"))
}

func TestPublishBootstrapOutputWithNoRemainingTypes(t *testing.T) {
	root := t.TempDir()
	output := filepath.Join(root, "document")
	require.NoError(t, os.MkdirAll(filepath.Join(output, "removed"), 0755))
	obsolete := filepath.Join(output, "removed", "last.md")
	require.NoError(t, os.WriteFile(obsolete, []byte("obsolete"), 0644))
	metadata := filepath.Join(output, ".DS_Store")
	require.NoError(t, os.WriteFile(metadata, []byte("metadata"), 0644))
	require.NoError(t, publishBootstrapOutput(filepath.Join(root, "empty-staging"), output, ".md"))
	require.NoFileExists(t, obsolete)
	require.FileExists(t, metadata)
}
